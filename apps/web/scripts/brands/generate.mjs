/* global fetch */
// Regenerates src/brands/*.generated.ts from the Simple Icons dataset (CC0-1.0), pinned to
// released versions, plus any sanitised official logos in src/brands/custom/.
// Run from apps/web: node scripts/brands/generate.mjs
//
// Marks missing from every pinned release are NOT drawn or approximated: the entry stays in the
// registry (name, aliases, domains) and renders the monogram tile.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { BRANDS as BASE } from './brands.mjs';
import { EXTRA } from './brands.extra.mjs';
import { MORE } from './brands.more.mjs';
import { BATCH4 } from './brands.batch4.mjs';
import { sanitizeSvg } from './sanitize.mjs';

// Primary release still carries Microsoft/AWS/Slack marks; newer additions come from later releases.
const VERSIONS = ['11.15.0', '15.22.0', '16.3.0', '90646e4bf7f3b89df6c37e65baf3e7bc759a517c'];
const base = (v) => `https://raw.githubusercontent.com/simple-icons/simple-icons/${v}`;
const out = (name) => new URL(`../../src/brands/${name}`, import.meta.url);

const BRANDS = [...BASE, ...EXTRA, ...MORE, ...BATCH4];
const seen = new Set();
for (const [id] of BRANDS) {
  if (seen.has(id)) throw new Error(`duplicate brand id ${id}`);
  seen.add(id);
}

const hexByVersion = {};
const liveVersions = [];
for (const v of VERSIONS) {
  try {
    let res = await fetch(`${base(v)}/data/simple-icons.json`);
    if (!res.ok) res = await fetch(`${base(v)}/_data/simple-icons.json`);
    if (!res.ok) throw new Error(String(res.status));
    const data = await res.json();
    const m = new Map();
    for (const i of data.icons ?? data) m.set(i.slug ?? i.title.toLowerCase().replace(/[^a-z0-9]/g, ''), i.hex);
    hexByVersion[v] = m;
    liveVersions.push(v);
  } catch (error) {
    console.warn(`skipping release ${v}: ${error.message}`);
  }
}

const lum = (hex) => {
  const c = [0, 2, 4].map(i => parseInt(hex.slice(i, i + 2), 16) / 255).map(v => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};

// Official logos supplied by the project: src/brands/custom/<id>.svg + manifest.json {id: {source, licence}}.
const customDir = new URL('../../src/brands/custom/', import.meta.url);
const manifest = existsSync(new URL('manifest.json', customDir)) ? JSON.parse(readFileSync(new URL('manifest.json', customDir), 'utf8')) : {};
const custom = {};
if (existsSync(customDir)) {
  for (const file of readdirSync(customDir).filter(f => f.endsWith('.svg'))) {
    const id = file.slice(0, -4);
    if (!seen.has(id)) throw new Error(`custom/${file}: no brand with id ${id}`);
    const entry = manifest[id];
    if (!entry || !String(entry.source ?? '').trim() || !String(entry.licence ?? '').trim()) throw new Error(`custom/${file}: manifest.json needs {source, licence} for ${id}`);
    custom[id] = sanitizeSvg(readFileSync(new URL(file, customDir), 'utf8'));
  }
}

const reg = [];
const paths = {};
const noMark = [];
const oversize = [];
const MAX_PATH = 8000;
async function findMark(slugList) {
  for (const slug of slugList) {
    for (const v of liveVersions) {
      const res = await fetch(`${base(v)}/icons/${slug}.svg`);
      if (!res.ok) continue;
      const all = [...(await res.text()).matchAll(/<path d="([^"]+)"/g)];
      if (all.length !== 1) continue;
      return { d: all[0][1], hex: String(hexByVersion[v].get(slug) ?? '').toUpperCase() };
    }
  }
  return undefined;
}
// Fetch in parallel (bounded), keep registry order.
const found = new Array(BRANDS.length);
let next = 0;
await Promise.all(Array.from({ length: 24 }, async () => {
  while (next < BRANDS.length) {
    const i = next++;
    const [id, , slugs] = BRANDS[i];
    const slugList = slugs === null || slugs === undefined ? [] : Array.isArray(slugs) ? slugs : [slugs];
    found[i] = custom[id] ? { d: custom[id], hex: '' } : await findMark(slugList);
  }
}));
BRANDS.forEach(([id, name, , aliases, hosts, category], i) => {
  let { d, hex } = found[i] ?? {};
  // Very detailed crests/wordmarks would dominate the bundle: they get the monogram tile instead.
  if (d && d.length > MAX_PATH && !custom[id]) { oversize.push(id); d = undefined; }
  // Brand colour only when it reads on both light and dark surfaces; otherwise the mark follows the text colour.
  const L = hex ? lum(hex) : -1;
  const entry = { id, name, aliases, hosts, category };
  if (d) {
    if (hex && L >= 0.08 && L <= 0.45) entry.color = `#${hex}`;
    paths[id] = d;
  } else {
    entry.noMark = true;
    noMark.push(id);
  }
  reg.push(entry);
});

const head = `// GENERATED by scripts/brands/generate.mjs from Simple Icons ${liveVersions.join(' + ')} (CC0-1.0). Do not edit.\n`;
mkdirSync(new URL('../../src/brands/', import.meta.url), { recursive: true });
writeFileSync(out('registry.generated.ts'),
  `${head}import type {BrandEntry} from './types.ts';\nexport const BRANDS:readonly BrandEntry[]=${JSON.stringify(reg)};\n`);

// One lazy chunk per category, so a page showing mail providers does not download every shop and bank.
const cats = [...new Set(reg.map(r => r.category))].sort();
for (const f of readdirSync(new URL('../../src/brands/', import.meta.url))) {
  if (/^paths\..*generated\.ts$/.test(f)) rmSync(out(f));
}
for (const cat of cats) {
  const subset = Object.fromEntries(reg.filter(r => r.category === cat && paths[r.id]).map(r => [r.id, paths[r.id]]));
  writeFileSync(out(`paths.${cat}.generated.ts`),
    `${head}/** Single-path marks (24x24 viewBox) for the "${cat}" category; loaded lazily, see registry.ts. */\nexport const PATHS:Readonly<Record<string,string>>=${JSON.stringify(subset)};\n`);
}
writeFileSync(out('loaders.generated.ts'),
  `${head}export const LOADERS:Readonly<Record<string,()=>Promise<{PATHS:Readonly<Record<string,string>>}>>>={\n${cats.map(c => `  ${JSON.stringify(c)}: () => import('./paths.${c}.generated.ts'),`).join('\n')}\n};\n`);
console.log(`ok ${reg.length} brands, ${Object.keys(paths).length} marks, ${noMark.length} monograms`);
console.log('over the size cap (monogram):', oversize.join(', '));
console.log('monogram:', noMark.join(', '));
