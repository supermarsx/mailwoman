import {afterEach,beforeAll,expect,it} from 'vitest';
import {createSignal} from 'solid-js';
import {cleanup,fireEvent,render,screen,within} from '@solidjs/testing-library';
import {TemplateLibraryEditor} from './TemplateLibraryEditor.tsx';
import type {ResponseTemplate} from './responseTemplateModel.ts';
import {chooseEditorFormat} from './nativeHtmlTestHarness.ts';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {initSync} from '../../wasm/mw-sanitize/mw_sanitize.js';
beforeAll(async()=>{initSync({module:readFileSync(resolve('src/wasm/mw-sanitize/mw_sanitize_bg.wasm'))});await Promise.all([import('./RichTextEditor.tsx'),import('./HtmlSourceEditor.tsx')]);},60000);
afterEach(cleanup);
it('ranges and toggles templates and removes only the selection',()=>{
 const [rows,setRows]=createSignal<ResponseTemplate[]>(['a','b','c','d'].map(id=>({id,title:`Template ${id}`,body:id})));
 render(()=><TemplateLibraryEditor value={rows()} onChange={setRows}/>);
 fireEvent.click(screen.getByRole('button',{name:'Template a'}),{ctrlKey:true});fireEvent.click(screen.getByRole('button',{name:'Template c'}),{shiftKey:true});fireEvent.click(screen.getByRole('button',{name:'Template b'}),{metaKey:true});fireEvent.click(screen.getByRole('button',{name:'Template d'}),{ctrlKey:true});
 expect(screen.queryByLabelText('Message text')).toBeNull();
 expect([...document.querySelectorAll<HTMLElement>('[data-bulk-selected="true"]')].map(row=>row.dataset.selectionId)).toEqual(['a','c','d']);
 fireEvent.click(within(screen.getByRole('toolbar',{name:'Selection actions'})).getByRole('button',{name:'Remove template'}));
 expect(rows().map(row=>row.id)).toEqual(['b']);
});
it('adds, edits, searches and removes plain text without interpreting HTML',async()=>{
 const [rows,setRows]=createSignal<ResponseTemplate[]>([]);render(()=><TemplateLibraryEditor value={rows()} onChange={setRows}/>);
 fireEvent.click(screen.getByRole('button',{name:'Add template'}));
 fireEvent.input(screen.getByLabelText('Template name'),{target:{value:'Follow up'}});
 await chooseEditorFormat(`template-${rows()[0]!.id}-format`,'plain');
 fireEvent.input(screen.getByLabelText('Message text'),{target:{value:'<img src=x>\nThanks'}});
 expect(rows()[0]?.body).toBe('<img src=x>\nThanks');expect(document.querySelector('img')).toBeNull();
 fireEvent.click(screen.getByRole('button',{name:'Back'}));
 fireEvent.input(screen.getByLabelText('Find a template'),{target:{value:'Thanks'}});expect(screen.getByRole('button',{name:'Follow up'})).toBeVisible();
 fireEvent.click(screen.getByRole('button',{name:'Remove template'}));expect(rows()).toEqual([]);
});
it('keeps a locked library readable but disables mutations',()=>{render(()=><TemplateLibraryEditor value={[{id:'one',title:'Read only',body:'Original'}]} onChange={()=>{throw Error('write');}} disabled/>);expect(screen.getByRole('button',{name:'Add template'})).toBeDisabled();fireEvent.click(screen.getByRole('button',{name:'Read only'}));expect(screen.getByLabelText('Message text')).toBeDisabled();fireEvent.click(screen.getByRole('button',{name:'Back'}));expect(screen.getByRole('button',{name:'Remove template'})).toBeDisabled();});
