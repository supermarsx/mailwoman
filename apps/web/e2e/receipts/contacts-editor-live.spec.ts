import {test,expect} from '../csrf.ts';
test('creates and edits a contact on dedicated pages with explicit discard',async({page},info)=>{
 await page.goto('/');await page.getByLabel('Email or username',{exact:true}).fill('testuser');await page.getByLabel('Password',{exact:true}).fill('testpass');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('region',{name:'Messages',exact:true})).toBeVisible();
 await page.goto('/#/contacts');
 await page.getByRole('button',{name:'New contact',exact:true}).click();
 await expect(page.getByRole('heading',{name:'New contact',exact:true})).toBeVisible();
 await expect(page.getByRole('searchbox',{name:'Search contacts'})).toHaveCount(0);
 const name=`Contact editor ${info.project.name} ${Date.now()}`;
 await page.getByLabel('Full name',{exact:true}).fill(name);await page.getByLabel('Email 1',{exact:true}).fill('contact@example.org');
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.getByRole('alertdialog')).toBeVisible();await page.getByRole('button',{name:'Keep editing',exact:true}).click();
 await expect(page.getByLabel('Full name',{exact:true})).toHaveValue(name);
 await page.evaluate(()=>{location.hash='#/mail';});
 await expect(page.getByRole('alertdialog')).toBeVisible();await page.getByRole('button',{name:'Keep editing',exact:true}).click();
 await expect(page).toHaveURL(/#\/contacts$/);
 await expect(page.getByLabel('Full name',{exact:true})).toHaveValue(name);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('contact-exclusive-editor.png'),fullPage:true});
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('article',{name:`Contact ${name}`,exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Edit',exact:true}).click();await page.getByLabel('Full name',{exact:true}).fill(`${name} edited`);
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('article',{name:`Contact ${name} edited`,exact:true})).toBeVisible();
 await page.reload();await page.getByText(`${name} edited`,{exact:true}).first().click();
 await expect(page.getByRole('article',{name:`Contact ${name} edited`,exact:true})).toBeVisible();
 await page.screenshot({path:info.outputPath('contact-persisted.png'),fullPage:true});
});
