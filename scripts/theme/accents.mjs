// Accent shade generator (t32-ext §V).
//
// Shades each of the ten named accents for every built-in theme and writes the
// table to `apps/web/src/theme/accents.ts`, which `themes.css.ts` turns into
// `:root[data-theme="…"][data-accent="…"]` rules. The math is in
// `apps/web/src/theme/accentMath.ts` (OKLCH, hue fixed, the lightness nearest
// to the accent's own that clears 3:1 on every surface of the theme and carries
// an ink at 4.5:1); the theme colours come from `tokens.ts`. Both are imported
// as TypeScript, which Node runs by stripping the types (Node 22.18 or later),
// so the script has no dependency and no copy of either.
//
// `accents.test.ts` recomputes the table with the same module and fails when the
// committed file differs, so run this after changing a theme palette or an
// accent definition.
//
// Usage: `node scripts/theme/accents.mjs`          (rewrite accents.ts)
//        `node scripts/theme/accents.mjs --check`  (exit 1 when accents.ts is stale)

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const themeDir = new URL('../../apps/web/src/theme/', import.meta.url);
const outPath = fileURLToPath(new URL('accents.ts', themeDir));

const { THEMES } = await import(new URL('tokens.ts', themeDir).href);
const { ACCENT_IDS, computeAccentTable } = await import(new URL('accentMath.ts', themeDir).href);

const palettes = Object.fromEntries(Object.entries(THEMES).map(([id, t]) => [id, t.color]));
const table = computeAccentTable(palettes);

const key = (id) => (/^[a-z]+$/.test(id) ? id : `'${id}'`);
const rows = Object.entries(table).map(([theme, cells]) => {
  const inner = ACCENT_IDS.map(
    (a) => `    ${a}: { accent: '${cells[a].accent}', accentText: '${cells[a].accentText}' },`,
  ).join('\n');
  return `  ${key(theme)}: {\n${inner}\n  },`;
});

const source = `// GENERATED by scripts/theme/accents.mjs from tokens.ts and accentMath.ts.
// Do not edit by hand: change a palette or an accent definition and run
// \`node scripts/theme/accents.mjs\`. accents.test.ts fails when this file is
// stale and checks every cell against the theme's contrast requirements.

import type { ThemeName } from './contract.css.ts';
import type { AccentId, AccentShade } from './accentMath.ts';

/** Each named accent shaded for each built-in theme. */
export const ACCENT_SHADES: Readonly<Record<ThemeName, Readonly<Record<AccentId, AccentShade>>>> = {
${rows.join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const current = (await readFile(outPath, 'utf8')).replace(/\r\n/g, '\n');
  if (current !== source) {
    console.error('accents.ts is stale: run `node scripts/theme/accents.mjs`');
    process.exit(1);
  }
  console.log('accents.ts is up to date');
} else {
  await writeFile(outPath, source);
  console.log(`wrote ${outPath}: ${rows.length} themes x ${ACCENT_IDS.length} accents`);
}
