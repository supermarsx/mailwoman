// Regenerates apps/web/locales/TRANSLATION-STATUS.json (t32-admin §2.9).
//
// For every shipped non-en locale the file records:
//   source    how the translations were made: "none" (no translated ids yet),
//             "machine" (machine translation), "human", or "unspecified"
//   reviewed  whether a native speaker reviewed them (never set by this script)
//   ids       how many en message ids the locale defines
//   pending   the en ids the locale does not define yet, sorted; they render in
//             English through the runtime fallback chain
//
// `source` and `reviewed` are kept from the existing file (translators set them);
// `ids` and `pending` are recomputed from the catalogs. Run it after adding en
// ids or translating; check-catalog.mjs compares the catalogs with this file.
//
// Usage: node scripts/i18n/status.mjs [--check]
//   --check  write nothing; exit 1 if the file is out of date

import { writeFile } from 'node:fs/promises';
import { relative } from 'node:path';
import { SOURCE, idsForLocale, readStatus, repoRoot, shippedLocales, statusPath } from './lib/catalog.mjs';

const CHECK = process.argv.includes('--check');

const locales = await shippedLocales('status');
const enIds = [...(await idsForLocale(SOURCE))].sort();
const stored = await readStatus();
const previous = stored ?? { locales: {} };

const out = {
  _comment:
    'Generated by scripts/i18n/status.mjs; edit only `source` and `reviewed` by hand. ' +
    '`pending` lists the en ids a locale does not translate yet (they show in English). ' +
    'check-catalog.mjs requires every en id to be translated or pending.',
  sourceLocale: SOURCE,
  sourceIds: enIds.length,
  locales: {},
};

for (const locale of locales) {
  if (locale === SOURCE) continue;
  const have = await idsForLocale(locale);
  const ids = enIds.filter((id) => have.has(id)).length;
  const prev = previous.locales?.[locale] ?? {};
  out.locales[locale] = {
    source: ids === 0 ? 'none' : (prev.source && prev.source !== 'none' ? prev.source : 'unspecified'),
    reviewed: prev.reviewed === true && ids > 0,
    ids,
    pending: enIds.filter((id) => !have.has(id)),
  };
}

const text = JSON.stringify(out, null, 2) + '\n';
const before = stored === null ? '' : JSON.stringify(stored, null, 2) + '\n';

if (CHECK) {
  if (text !== before) {
    console.error(`status: ${relative(repoRoot, statusPath)} is out of date; run node scripts/i18n/status.mjs`);
    process.exit(1);
  }
  console.log(`status: ${relative(repoRoot, statusPath)} is up to date.`);
  process.exit(0);
}

await writeFile(statusPath, text, 'utf8');
console.log(`status: wrote ${relative(repoRoot, statusPath)} (${enIds.length} en ids).`);
for (const [locale, s] of Object.entries(out.locales)) {
  console.log(`  ${locale.padEnd(6)} ${String(s.ids).padStart(5)} translated, ${String(s.pending.length).padStart(5)} pending, source ${s.source}`);
}
