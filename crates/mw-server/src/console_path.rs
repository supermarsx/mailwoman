/// The console path chosen for this deployment (`/…`, relative to the deploy
/// prefix). The next start applies it unless `MW_ADMIN_PATH` is set.
pub const STORED_KEY: &str = "admin.consolePath";

/// The console path the last start applied. A start that applies another one
/// ends every admin session.
pub const APPLIED_KEY: &str = "admin.consolePath.applied";

/// Where the path in force came from.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum Source {
    /// `MW_ADMIN_PATH`.
    Env,
    /// The stored path.
    Stored,
    /// Generated by this start on a new installation.
    Generated,
    /// `/admin` kept by this start on an upgraded installation.
    Upgrade,
    /// The library default; nothing resolved a path (test servers).
    Default,
}

static PROVISION: AtomicBool = AtomicBool::new(false);
static SOURCE: RwLock<Source> = RwLock::new(Source::Default);

/// Have this process generate (new installation) or keep (upgrade) and store the
/// console path when neither `MW_ADMIN_PATH` nor a stored path names one.
/// `mailwoman serve` calls it before building the app; test binaries that build
/// the app in process do not, and keep the library default `/admin`.
pub fn provision_on_first_start() {
    PROVISION.store(true, Ordering::SeqCst);
}

#[doc(hidden)]
/// Test seam: undo [`provision_on_first_start`].
pub fn stop_provisioning() {
    PROVISION.store(false, Ordering::SeqCst);
}

fn source() -> Source {
    *SOURCE
        .read()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
}

/// A short, stable fingerprint of a path for the audit log and the server log
/// lines that must not print the path itself.
fn fingerprint(path: &str) -> String {
    let d = Sha256::digest(path.as_bytes());
    d[..4].iter().map(|b| format!("{b:02x}")).collect()
}

/// Does the database already hold a deployment? Anything an earlier version
/// would have written by the time it served a request counts.
async fn prior_install(store: &Store) -> anyhow::Result<bool> {
    if !store.settings_with_prefix("").await?.is_empty() {
        return Ok(true);
    }
    if store.count_admin_accounts().await? > 0 {
        return Ok(true);
    }
    if !store.list_audit(1).await?.is_empty() {
        return Ok(true);
    }
    Ok(!store.list_accounts().await?.is_empty())
}

/// End every admin session; returns how many ended.
async fn end_admin_sessions(store: &Store) -> anyhow::Result<u64> {
    let mut admins: Vec<String> = store
        .list_admin_sessions(0)
        .await?
        .into_iter()
        .map(|s| s.admin_id)
        .collect();
    admins.sort();
    admins.dedup();
    let mut ended = 0;
    for admin in admins {
        ended += store.delete_admin_sessions_of(&admin).await?;
    }
    Ok(ended)
}

async fn audit_system(store: &Store, actor: &str, action: &str, detail: Value) {
    let row = mw_store::AuditRow {
        id: uuid::Uuid::new_v4().to_string(),
        ts: chrono::Utc::now().to_rfc3339(),
        actor: actor.into(),
        actor_kind: if actor == "cli" { "cli" } else { "system" }.into(),
        action: action.into(),
        target: Some("admin:console-path".into()),
        detail_json: detail.to_string(),
        ip: None,
    };
    if let Err(e) = store.append_audit(&row).await {
        tracing::warn!("console path: audit append failed: {e}");
    }
}

fn warn_if_legacy(path: &str) {
    if path.eq_ignore_ascii_case(DEFAULT_ADMIN_PATH) {
        tracing::warn!(
            "the admin console is at {DEFAULT_ADMIN_PATH}, the first path a scanner tries. \
             Give it a path of its own: in the console (Security > Console address), with \
             `mailwoman admin console-path generate`, or with MW_ADMIN_PATH. See \
             docs/deploy/README.md, \"Moving the admin console\"."
        );
    }
}

/// Decide the console path for this process and apply it
/// (`mw_admin::config::set_admin_path`). Runs once at start, after the store is
/// open and before any route is built.
///
/// # Errors
/// When the stored path is not a valid admin path, or the store cannot be read
/// or written.
pub(crate) async fn resolve(store: &Store, overlay: &EnvOverlay) -> anyhow::Result<()> {
    let provision = PROVISION.load(Ordering::SeqCst);
    let stored = store.get_setting(STORED_KEY).await?;
    let base = crate::base_path_from_env();
    let (path, src) = if let Some(env) = &overlay.admin_path {
        (env.clone(), Source::Env)
    } else if let Some(stored) = stored.clone() {
        validate_admin_path(&stored).map_err(|why| {
            anyhow!(
                "the stored admin console path is not valid: {why}; set one with \
                 `mailwoman admin console-path set` or MW_ADMIN_PATH"
            )
        })?;
        crate::admin_apply::check_admin_path_against_base(&stored, &base)?;
        (stored, Source::Stored)
    } else if provision {
        if prior_install(store).await? {
            store.set_setting(STORED_KEY, DEFAULT_ADMIN_PATH).await?;
            tracing::info!(
                "upgraded installation without a configured admin console path: keeping {DEFAULT_ADMIN_PATH}"
            );
            (DEFAULT_ADMIN_PATH.to_string(), Source::Upgrade)
        } else {
            let generated = generate_admin_path().map_err(|e| anyhow!("{e}"))?;
            store.set_setting(STORED_KEY, &generated).await?;
            // Shown once. On stdout only: the application log store cuts the
            // path out of what it keeps (`observability::redact_log`).
            tracing::warn!(
                "new installation: the admin console is at {base}{generated}/ (generated; \
                 this is the only time it is logged; `mailwoman admin console-path show` \
                 prints it again)"
            );
            audit_system(
                store,
                "system",
                "admin-console-path-generated",
                json!({"to": fingerprint(&generated)}),
            )
            .await;
            (generated, Source::Generated)
        }
    } else {
        (DEFAULT_ADMIN_PATH.to_string(), Source::Default)
    };
    mw_admin::config::set_admin_path(Some(&path));
    *SOURCE
        .write()
        .unwrap_or_else(std::sync::PoisonError::into_inner) = src;
    if src == Source::Default {
        return Ok(());
    }
    if src == Source::Env && stored.as_deref().is_some_and(|s| s != path) {
        tracing::info!(
            "MW_ADMIN_PATH is set, so the stored admin console path is not used while it is"
        );
    }
    warn_if_legacy(&path);
    if src == Source::Env
        && !path.eq_ignore_ascii_case(DEFAULT_ADMIN_PATH)
        && path.len() - 1 < MIN_CHOSEN_ADMIN_PATH_LEN
    {
        tracing::warn!(
            "MW_ADMIN_PATH is shorter than {MIN_CHOSEN_ADMIN_PATH_LEN} characters, so it is easier to guess; `mailwoman admin console-path generate` makes a long one"
        );
    }
    if !provision {
        // An in-process test server: nothing to record, no sessions to end.
        return Ok(());
    }
    let applied = store.get_setting(APPLIED_KEY).await?;
    if applied.as_deref() != Some(path.as_str()) {
        if let Some(previous) = applied {
            let ended = end_admin_sessions(store).await?;
            tracing::warn!(
                "the admin console moved (path {} -> {}); ended {ended} admin session(s): \
                 sign in again at the new path",
                fingerprint(&previous),
                fingerprint(&path)
            );
            audit_system(
                store,
                "system",
                "admin-console-path-applied",
                json!({"from": fingerprint(&previous), "to": fingerprint(&path), "sessionsEnded": ended}),
            )
            .await;
        }
        store.set_setting(APPLIED_KEY, &path).await?;
    }
    Ok(())
}

// ─── admin API ───────────────────────────────────────────────────────────────────

pub(crate) fn register(r: &mut impl AdminRegistrar) {
    r.admin_endpoint(Method::GET, "/console-path", Capability::SecurityRead, read);
    r.admin_endpoint(
        Method::PUT,
        "/console-path",
        Capability::SecurityPolicyWrite,
        save,
    );
}

async fn snapshot(state: &AppState) -> Result<Value, AdminApiError> {
    let stored = state
        .store
        .get_setting(STORED_KEY)
        .await
        .map_err(AdminApiError::internal)?;
    let path = admin_path();
    let src = source();
    let pending = stored.filter(|s| src != Source::Env && *s != path);
    Ok(json!({
        "path": path,
        "source": src,
        "pending": pending,
        "pinnedBy": (src == Source::Env).then_some(EnvOverlay::ADMIN_PATH_VAR),
        "legacyDefault": path.eq_ignore_ascii_case(DEFAULT_ADMIN_PATH),
        "minLength": MIN_CHOSEN_ADMIN_PATH_LEN,
    }))
}

async fn read(State(state): State<AppState>, ctx: AdminCtx) -> Result<Response, AdminApiError> {
    ctx.require_unscoped(Capability::SecurityRead)?;
    let body = snapshot(&state).await?;
    let tag = etag_of(&body);
    Ok(with_etag(
        ([("cache-control", "private, no-store")], Json(body)),
        &tag,
    ))
}

/// The body of `PUT {console}/console-path`: a path of the admin's choosing, or
/// `generate: true` for a random one.
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Change {
    #[serde(default)]
    path: Option<String>,
    #[serde(default)]
    generate: bool,
}

async fn save(
    State(state): State<AppState>,
    ctx: AdminCtx,
    headers: HeaderMap,
    AdminJson(change): AdminJson<Change>,
) -> Result<Response, AdminApiError> {
    ctx.require_unscoped(Capability::SecurityPolicyWrite)?;
    crate::step_up::require_admin(&state, &ctx, crate::step_up::StepUpAction::ConsolePath).await?;
    if source() == Source::Env {
        return Err(AdminApiError::conflict(
            "pinnedByEnvironment",
            "MW_ADMIN_PATH sets the console path. Change or remove it on the server.",
        ));
    }
    let before = snapshot(&state).await?;
    check_if_match(&headers, &etag_of(&before), None, None)?;
    let current = admin_path();
    let next = match (change.path, change.generate) {
        (Some(_), true) | (None, false) => {
            return Err(AdminApiError::invalid(
                "invalidConsolePath",
                "Give a path or ask for a generated one, not both.",
                "/path",
            ));
        }
        (None, true) => generate_admin_path().map_err(AdminApiError::internal)?,
        // Going back to the path in force cancels a pending change.
        (Some(p), false) if p == current => p,
        (Some(p), false) => validate_chosen_admin_path(&p)
            .map_err(|why| AdminApiError::invalid("invalidConsolePath", why, "/path"))?,
    };
    crate::admin_apply::check_admin_path_against_base(&next, &state.base_path)
        .map_err(|e| AdminApiError::invalid("invalidConsolePath", e.to_string(), "/path"))?;
    state
        .store
        .set_setting(STORED_KEY, &next)
        .await
        .map_err(AdminApiError::internal)?;
    crate::admin_accounts::audit(
        &state,
        &ctx,
        "admin-console-path-changed",
        "admin:console-path",
        Some(json!({"path": fingerprint(&current)})),
        Some(json!({"path": fingerprint(&next), "appliesAtRestart": next != current})),
    )
    .await;
    let mut body = snapshot(&state).await?;
    let tag = etag_of(&body);
    body["restartRequired"] = json!(next != current);
    Ok(with_etag(
        (
            StatusCode::OK,
            [("cache-control", "private, no-store")],
            Json(body),
        ),
        &tag,
    ))
}

// ─── CLI ─────────────────────────────────────────────────────────────────────────

/// `mailwoman admin console-path …`: show the console path, or store a new one
/// for the next start. The operator's way back in when the path is forgotten.
///
/// # Errors
/// When `MW_ADMIN_PATH` pins the path (for a change), the path is not valid, or
/// the store cannot be read or written.
pub async fn cli(store: &Store, verb: mw_admin::cli::ConsolePathVerb) -> anyhow::Result<String> {
    use mw_admin::cli::ConsolePathVerb;
    let env = std::env::var(EnvOverlay::ADMIN_PATH_VAR).ok();
    let base = crate::base_path_from_env();
    let stored = store.get_setting(STORED_KEY).await?;
    let applied = store.get_setting(APPLIED_KEY).await?;
    let next = match verb {
        ConsolePathVerb::Show => {
            let mut out = Vec::new();
            match (&env, &stored) {
                (Some(e), _) => out.push(format!("{base}{e}/ (MW_ADMIN_PATH)")),
                (None, Some(s)) => out.push(format!("{base}{s}/")),
                (None, None) => out.push(
                    "not configured yet: the next `mailwoman serve` generates one \
                     (or keeps /admin on an upgraded installation)"
                        .into(),
                ),
            }
            let effective = env.as_ref().or(stored.as_ref());
            if let (Some(a), Some(e)) = (&applied, effective)
                && a != e
            {
                out.push(format!(
                    "the running server may still use {base}{a}/ until it restarts"
                ));
            }
            return Ok(out.join("\n"));
        }
        _ if env.is_some() => {
            return Err(anyhow!(
                "MW_ADMIN_PATH sets the console path; change or remove it instead"
            ));
        }
        ConsolePathVerb::Generate => generate_admin_path().map_err(|e| anyhow!("{e}"))?,
        ConsolePathVerb::Set { path } => {
            validate_chosen_admin_path(&path).map_err(|why| anyhow!("{path:?}: {why}"))?
        }
    };
    crate::admin_apply::check_admin_path_against_base(&next, &base)?;
    store.set_setting(STORED_KEY, &next).await?;
    audit_system(
        store,
        "cli",
        "admin-console-path-changed",
        json!({"from": stored.as_deref().map(fingerprint), "to": fingerprint(&next)}),
    )
    .await;
    Ok(format!(
        "stored. Restart the server to apply it; the console will then be at {base}{next}/ \
         and admin sessions at the old path end."
    ))
}

