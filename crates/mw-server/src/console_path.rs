//! t76 — the admin console is served only at its configured path.
//!
//! `mw_admin::config::admin_path` is the one place every admin route, the console
//! page and the admin cookie take their path from (t32-h15). This module decides,
//! once at start, what that path is:
//!
//! 1. `MW_ADMIN_PATH`, when set. It pins the path: the console and the CLI refuse
//!    to change it while the variable is set.
//! 2. Otherwise the path stored in the database ([`STORED_KEY`]), written by an
//!    earlier start, the console ([`save`]) or `mailwoman admin console-path`.
//! 3. Otherwise, under `mailwoman serve` ([`provision_on_first_start`]):
//!    * a **new installation** (nothing in the database yet) gets a generated path
//!      (`mw_admin::config::generate_admin_path`, 20 random characters). It is
//!      stored and logged once; `mailwoman admin console-path show` prints it
//!      again.
//!    * an **upgraded installation** (the database already holds settings,
//!      accounts, admin accounts or audit entries) keeps `/admin`, the path it had,
//!      so nobody is locked out. That is stored too, and every start logs a
//!      warning recommending a path of its own.
//! 4. Otherwise (`build_app` inside a test binary) the library default, `/admin`,
//!    without writing anything.
//!
//! There is no alias: the console answers at exactly one path, and every other
//! path, `/admin` included once the path moved, gets the unknown-path answer.
//!
//! A change made in the console or the CLI is stored and takes effect at the next
//! start. The routes are built once, at start, from the path. When a start applies
//! a path that differs from the one the previous start applied
//! ([`APPLIED_KEY`]), every admin session is ended: the admin cookie is scoped to
//! the old path, so those sessions could not be used at the new one anyway, and
//! ending them leaves no live session behind.
//!
//! What this is and is not: a path nobody can guess keeps scanners and drive-by
//! sign-in attempts off the console. It does not isolate the console. The console
//! shares the mail app's origin, so a script running in the mail app (an XSS, or a
//! provider script loaded by an analytics tag) that learns the path can still
//! reach it from a browser that holds an admin session.

