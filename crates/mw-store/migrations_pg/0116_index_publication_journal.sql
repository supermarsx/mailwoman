-- Schema parity with SQLite 0116 (see that file for the contract). The journal mode
-- is refused on PostgreSQL in t34: identity values are assigned at INSERT, not at
-- COMMIT, so "capture max(seq), read source, delete <= seq" could delete a row of a
-- transaction that committed later with a smaller seq. The control row stays absent
-- (disabled); the triggers exist so both dialects keep one definition set.
-- BY DEFAULT (not ALWAYS) so a same-installation store move can copy explicit seq values.
CREATE TABLE index_publication_journal (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id TEXT NOT NULL,
 stable_id TEXT NOT NULL,
 mode TEXT NOT NULL CHECK(mode IN ('metadata','reconcile','delete'))
);
CREATE INDEX index_publication_journal_key ON index_publication_journal(account_id,stable_id,seq);
CREATE TABLE index_publication_journal_control (
 id BIGINT PRIMARY KEY CHECK(id=1),
 enabled BIGINT NOT NULL DEFAULT 0 CHECK(enabled IN (0,1))
);

-- messages: same column list as SQLite. cache_revision is set by a BEFORE trigger
-- (0105) on every UPDATE and is excluded for the same reason as on SQLite.
CREATE FUNCTION index_journal_message_fn() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' THEN
  IF NOT (NEW.stable_id IS DISTINCT FROM OLD.stable_id OR NEW.account_id IS DISTINCT FROM OLD.account_id OR NEW.mailbox_id IS DISTINCT FROM OLD.mailbox_id OR NEW.uid IS DISTINCT FROM OLD.uid OR NEW.uidvalidity IS DISTINCT FROM OLD.uidvalidity OR NEW.message_id IS DISTINCT FROM OLD.message_id OR NEW.thread_id IS DISTINCT FROM OLD.thread_id OR NEW.internaldate IS DISTINCT FROM OLD.internaldate OR NEW.size IS DISTINCT FROM OLD.size OR NEW.flags_json IS DISTINCT FROM OLD.flags_json OR NEW.envelope_json IS DISTINCT FROM OLD.envelope_json OR NEW.blob_ref IS DISTINCT FROM OLD.blob_ref OR NEW.content_revision IS DISTINCT FROM OLD.content_revision) THEN
   RETURN NULL;
  END IF;
 END IF;
 IF NOT EXISTS (SELECT 1 FROM index_publication_journal_control WHERE id=1 AND enabled=1) THEN
  RETURN NULL;
 END IF;
 IF TG_OP='INSERT' THEN
  INSERT INTO index_publication_journal(account_id,stable_id,mode) VALUES(NEW.account_id,NEW.stable_id,'reconcile');
 ELSIF TG_OP='DELETE' THEN
  INSERT INTO index_publication_journal(account_id,stable_id,mode) VALUES(OLD.account_id,OLD.stable_id,'delete');
 ELSE
  IF NEW.account_id IS DISTINCT FROM OLD.account_id OR NEW.stable_id IS DISTINCT FROM OLD.stable_id THEN
   INSERT INTO index_publication_journal(account_id,stable_id,mode) VALUES(OLD.account_id,OLD.stable_id,'delete');
  END IF;
  INSERT INTO index_publication_journal(account_id,stable_id,mode) VALUES(NEW.account_id,NEW.stable_id,CASE WHEN NEW.envelope_json IS NOT DISTINCT FROM OLD.envelope_json AND NEW.blob_ref IS NOT DISTINCT FROM OLD.blob_ref AND NEW.content_revision IS NOT DISTINCT FROM OLD.content_revision AND NEW.account_id IS NOT DISTINCT FROM OLD.account_id AND NEW.stable_id IS NOT DISTINCT FROM OLD.stable_id THEN 'metadata' ELSE 'reconcile' END);
 END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER index_journal_message AFTER INSERT OR UPDATE OR DELETE ON messages FOR EACH ROW EXECUTE FUNCTION index_journal_message_fn();

CREATE FUNCTION index_journal_meta_fn() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' THEN
  IF NOT (NEW.stable_id IS DISTINCT FROM OLD.stable_id OR NEW.pinned IS DISTINCT FROM OLD.pinned OR NEW.snoozed_until IS DISTINCT FROM OLD.snoozed_until OR NEW.follow_up_at IS DISTINCT FROM OLD.follow_up_at) THEN
   RETURN NULL;
  END IF;
 END IF;
 IF NOT EXISTS (SELECT 1 FROM index_publication_journal_control WHERE id=1 AND enabled=1) THEN
  RETURN NULL;
 END IF;
 IF TG_OP='DELETE' THEN
  INSERT INTO index_publication_journal(account_id,stable_id,mode) SELECT m.account_id,m.stable_id,'metadata' FROM messages m WHERE m.stable_id=OLD.stable_id;
  RETURN NULL;
 END IF;
 IF TG_OP='UPDATE' THEN
  IF NEW.stable_id IS DISTINCT FROM OLD.stable_id THEN
   INSERT INTO index_publication_journal(account_id,stable_id,mode) SELECT m.account_id,m.stable_id,'metadata' FROM messages m WHERE m.stable_id=OLD.stable_id;
  END IF;
 END IF;
 INSERT INTO index_publication_journal(account_id,stable_id,mode) SELECT m.account_id,m.stable_id,'metadata' FROM messages m WHERE m.stable_id=NEW.stable_id;
 RETURN NULL;
END $$;
CREATE TRIGGER index_journal_meta AFTER INSERT OR UPDATE OR DELETE ON message_meta FOR EACH ROW EXECUTE FUNCTION index_journal_meta_fn();

CREATE FUNCTION index_journal_lease_fn() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' THEN
  IF NOT (NEW.stable_id IS DISTINCT FROM OLD.stable_id OR NEW.account_id IS DISTINCT FROM OLD.account_id OR NEW.blob_ref IS DISTINCT FROM OLD.blob_ref OR NEW.uidvalidity IS DISTINCT FROM OLD.uidvalidity OR NEW.uid IS DISTINCT FROM OLD.uid) THEN
   RETURN NULL;
  END IF;
 END IF;
 IF NOT EXISTS (SELECT 1 FROM index_publication_journal_control WHERE id=1 AND enabled=1) THEN
  RETURN NULL;
 END IF;
 IF TG_OP='DELETE' THEN
  INSERT INTO index_publication_journal(account_id,stable_id,mode) SELECT m.account_id,m.stable_id,'reconcile' FROM messages m WHERE m.stable_id=OLD.stable_id AND m.blob_ref IS NULL;
 ELSIF TG_OP='INSERT' THEN
  INSERT INTO index_publication_journal(account_id,stable_id,mode) SELECT m.account_id,m.stable_id,'reconcile' FROM messages m WHERE m.stable_id=NEW.stable_id AND m.blob_ref IS NULL;
 ELSE
  INSERT INTO index_publication_journal(account_id,stable_id,mode) SELECT m.account_id,m.stable_id,'reconcile' FROM messages m WHERE m.stable_id IN (OLD.stable_id,NEW.stable_id) AND m.blob_ref IS NULL;
 END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER index_journal_lease AFTER INSERT OR UPDATE OR DELETE ON message_body_cache_lease FOR EACH ROW EXECUTE FUNCTION index_journal_lease_fn();
